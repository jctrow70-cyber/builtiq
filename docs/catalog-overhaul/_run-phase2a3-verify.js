const { spawnSync } = require('child_process');
const fs = require('fs');
const path = require('path');
const node = process.execPath;
const cwd = process.cwd();
const out = path.join(cwd, 'docs', 'catalog-overhaul', 'phase2a3-live-verify-console.txt');
const cli = path.join(cwd, 'node_modules', 'tsx', 'dist', 'cli.mjs');
const script = path.join(cwd, 'scripts', 'verify-phase2a3-live.ts');
const r = spawnSync(node, [cli, script], { encoding: "utf8", cwd: cwd, env: process.env, timeout: 180000 });
const parts = [];
parts.push("=== STDOUT ===");
parts.push(r.stdout || "");
parts.push("=== STDERR ===");
parts.push(r.stderr || "");
parts.push("=== ERROR ===");
parts.push(r.error ? String(r.error) : "");
parts.push("=== EXIT ===");
parts.push(String(r.status));
fs.writeFileSync(out, parts.join("\n"));
process.exit(r.status == null ? 1 : r.status);